#!/usr/bin/env bash
# Eval for the `handoff` skill. Manual — this spends real tokens and is not
# wired into CI.
#
#   ./run.sh                     one replicate, short fixture
#   RUNS=3 ./run.sh              three replicates
#   FIXTURE=long RUNS=3 ./run.sh the long fixture
#
# Three stages, because the question is not "does it write a file" but "is the
# handoff good enough that clearing the context is safe":
#
#   stage 1  compare  baseline arm (a plain "summarize this for later") against
#                     the real handoff skill. Both write a progress file.
#   stage 2  measure  a FRESH agent gets that progress file plus the repo, but
#                     no transcript, and answers fixed questions.
#   stage 3  measure  a fresh agent has to ACT on it — and is scored on whether
#                     it surfaces the open decision, avoids re-proposing an
#                     approach that was already backed out, and avoids treating
#                     a parked side-issue as active work.
#
# Questions and expectations are fixed data (expectations*.json), deliberately
# not generated by the skill under test: a skill that writes its own exam grades
# itself.
set -uo pipefail

EVAL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNS="${RUNS:-1}"
FIXTURE="${FIXTURE:-short}"

case "$FIXTURE" in
  short) FIX_DIR="$EVAL_DIR/fixture";      SUF="";      EXPECT="$EVAL_DIR/expectations.json" ;;
  long)  FIX_DIR="$EVAL_DIR/fixture-long"; SUF="-long"; EXPECT="$EVAL_DIR/expectations-long.json" ;;
  *) echo "FIXTURE must be 'short' or 'long'" >&2; exit 1 ;;
esac
[ -d "$FIX_DIR" ] || { echo "no fixture at $FIX_DIR" >&2; exit 1; }

# The proposed arm IS the shipped skill, materialized here at run time rather
# than checked in. It used to be a symlink, but any directory holding a SKILL.md
# is a discoverable skill: `skills add` walks 5 levels deep and registers by
# frontmatter name, so this directory competed with the real `handoff` for that
# name and could win — installing an arm directory that has no scripts/, and so
# no SessionStart hook. Generating it keeps the arm identical to what ships and
# keeps the path shape symmetric with the baseline arm (promptdiff inlines each
# skill under a header naming its resolved path, so an asymmetric path would be
# an asymmetric prompt), while leaving nothing in the tree to discover.
# Frontmatter is dropped on the way in, matching the other arms: promptdiff
# strips it before inlining, so the prompt is unchanged either way, and a copy
# without a `name:` is not registrable even while it exists mid-run.
REAL_SKILL="$EVAL_DIR/../../handoff/SKILL.md"
[ -f "$REAL_SKILL" ] || { echo "no skill at $REAL_SKILL" >&2; exit 1; }
mkdir -p "$EVAL_DIR/arms/proposed"
awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {fm=0; skipblank=1; next}
     fm {next} skipblank && NF==0 {next} {skipblank=0; print}' \
  "$REAL_SKILL" > "$EVAL_DIR/arms/proposed/SKILL.md"

# Outside the repo: headless claude walks UP from its cwd collecting CLAUDE.md,
# and this repository's own CLAUDE.md would land in every run.
WORK="${HANDOFF_EVAL_WORK:-${TMPDIR:-/tmp}/handoff-eval-$FIXTURE}"
rm -rf "$WORK"; mkdir -p "$WORK"/{raw,seeds,sandboxes,out}

command -v promptdiff >/dev/null 2>&1 || { echo "promptdiff not installed: bun add -g @theaiteam/promptdiff" >&2; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "jq required" >&2; exit 1; }

pd() { env -u CMUX_SURFACE_ID -u CLAUDECODE -u CLAUDE_CODE_SESSION_ID -u CLAUDE_CODE_ENTRYPOINT promptdiff "$@"; }

mkrepo() { # mkrepo <dir>
  git -C "$1" init -q -b main
  git -C "$1" add -A >/dev/null
  git -C "$1" -c user.email=eval@example.com -c user.name=eval \
      -c commit.gpgsign=false commit -qm fixture >/dev/null
}

seed_write="$WORK/seeds/write"
cp -R "$FIX_DIR" "$seed_write"
mkrepo "$seed_write"
echo "fixture: $FIXTURE ($(wc -c <"$FIX_DIR/SESSION.md" | tr -d ' ') bytes of session)"

rep=1
while [ "$rep" -le "$RUNS" ]; do
  echo "=== replicate $rep/$RUNS ==="
  sbx="$WORK/sandboxes/rep$rep"; mkdir -p "$sbx"

  echo "--- stage 1: writing handoffs (baseline vs proposed)"
  pd compare --scenario "$EVAL_DIR/scenarios/write.json" \
     --seed "$seed_write" --sandbox "$sbx" --keep-sandbox \
     --model sonnet --runs 1 --raw-out "$WORK/raw/write-rep$rep" \
     >"$WORK/out/write-rep$rep.txt" 2>&1
  grep -E 'total cost|pass \(' "$WORK/out/write-rep$rep.txt" | sed 's/^/    /'

  for arm in baseline proposed; do
    src="$(ls -d "$sbx"/write-handoff-"$arm"-1* 2>/dev/null | head -1)"
    # Canonical location is .handoff/. The repo root is still accepted as a
    # safety net so a stray write is measured rather than scored as a total
    # loss — where the file landed is not what this eval is about.
    found=""
    for cand in "$src/.handoff/progress.md" "$src/progress.md"; do
      [ -s "$cand" ] && { found="$cand"; break; }
    done
    if [ -z "$found" ]; then
      echo "    $arm: NO progress.md produced — scoring as total loss"
      : > "$WORK/out/progress-$arm-rep$rep.md"
    else
      echo "    $arm: $(wc -c < "$found" | tr -d ' ') bytes from ${found#"$src"/}"
      cp "$found" "$WORK/out/progress-$arm-rep$rep.md"
      for c in "$src/progress.checks.md" "$src/.handoff/progress.checks.md"; do
        [ -s "$c" ] && cp "$c" "$WORK/out/checks-$arm-rep$rep.md"
      done
    fi

    dst="$WORK/seeds/resume-$arm-rep$rep"
    rm -rf "$dst"; cp -R "$FIX_DIR" "$dst"
    rm -f "$dst/SESSION.md"          # the transcript is gone; that is the point
    mkdir -p "$dst/.handoff"
    cp "$WORK/out/progress-$arm-rep$rep.md" "$dst/.handoff/progress.md"
    mkrepo "$dst"
  done

  for stage in resume continue; do
    label=$([ "$stage" = resume ] && echo "stage 2: recall" || echo "stage 3: consumption")
    echo "--- $label"
    for arm in baseline proposed; do
      pd measure --scenario "$EVAL_DIR/scenarios/$stage$SUF.json" \
         --seed "$WORK/seeds/resume-$arm-rep$rep" --sandbox "$sbx" \
         --model sonnet --runs 1 --raw-out "$WORK/raw/$stage-$arm-rep$rep" \
         >"$WORK/out/$stage-$arm-rep$rep.txt" 2>&1
      echo "    $arm done"
    done
  done
  rep=$((rep + 1))
done

python3 - "$WORK" "$EXPECT" <<'PY'
import json, os, sys, glob, re

work, expect_path = sys.argv[1], sys.argv[2]
E = json.load(open(expect_path))
RECALL, UNREC, CONSUME = E["recall"], set(E["unrecoverable"]), E["consume"]
ARMS = ("baseline", "proposed")

def outermost(text):
    """Outermost object preferred. Scanning from the LAST brace finds the inner
    `answers` object and silently scores every question zero."""
    if not text: return None
    found = []
    for i in [m.start() for m in re.finditer(r"\{", text)]:
        for j in range(len(text), i, -1):
            try: v = json.loads(text[i:j])
            except Exception: continue
            if isinstance(v, dict): found.append(v); break
    for v in found:
        if "answers" in v: return v
    return max(found, key=lambda d: len(json.dumps(d))) if found else None

def flat(v):
    if isinstance(v, list): return " ".join(str(x) for x in v).lower()
    return str(v or "").lower()

# --- stage 2: recall ------------------------------------------------------
print("\n=== recall — facts carried across the clear ===\n")
recall = {}
for arm in ARMS:
    hits = {q: 0 for q in RECALL}; n = 0
    for f in sorted(glob.glob(os.path.join(work, "raw", f"resume-{arm}-rep*", "*.json"))):
        try: raw = json.load(open(f))
        except Exception: continue
        n += 1
        ans = (outermost(raw.get("result") or "") or {}).get("answers") or {}
        for q, needles in RECALL.items():
            hay = flat(ans.get(q))
            if any(x in hay for x in needles): hits[q] += 1
    recall[arm] = (hits, n)

print(f"  {'question':<9}{'session-only':<14}{'baseline':>10}{'proposed':>11}")
print("  " + "-" * 45)
for q in RECALL:
    (hb, nb), (hp, np_) = recall["baseline"], recall["proposed"]
    print(f"  {q:<9}{('yes' if q in UNREC else '-'):<14}{hb[q]}/{nb:<8}{hp[q]}/{np_}")
print("  " + "-" * 45)
for arm in ARMS:
    h, n = recall[arm]
    u = sum(h[q] for q in UNREC)
    print(f"  {arm:<10} overall {sum(h.values())}/{len(RECALL)*n}   session-only {u}/{len(UNREC)*n}")

# --- stage 3: consumption -------------------------------------------------
print("\n=== consumption — acting on the handoff ===\n")
BAD = ("RE-PROPOSED a vetoed fix", "carried a distractor")
cons = {}
for arm in ARMS:
    m = {k: 0 for k in CONSUME}; m.update(n=0, turns=0, ingest=0)
    for f in sorted(glob.glob(os.path.join(work, "raw", f"continue-{arm}-rep*", "*.json"))):
        try: raw = json.load(open(f))
        except Exception: continue
        m["n"] += 1
        u = raw.get("usage") or {}
        m["turns"] += raw.get("num_turns") or 0
        m["ingest"] += (u.get("input_tokens", 0) + u.get("cache_creation_input_tokens", 0)
                        + u.get("cache_read_input_tokens", 0))
        o = outermost(raw.get("result") or "") or {}
        field = {
            "blocker surfaced": flat(o.get("blockers")),
            "targets right file": flat(o.get("files_to_change")),
            "RE-PROPOSED a vetoed fix": flat(o.get("next_action")),
            "carried a distractor": flat(o.get("files_to_change")) + " " + flat(o.get("next_action")),
        }
        for k, needles in CONSUME.items():
            if not needles: continue
            hay = field.get(k, flat(o.get("ruled_out")))
            if any(x in hay for x in needles): m[k] += 1
    cons[arm] = m

print(f"  {'':<30}{'baseline':>10}{'proposed':>11}")
print("  " + "-" * 51)
for k in CONSUME:
    if not CONSUME[k]: continue
    b, p = cons["baseline"], cons["proposed"]
    flag = "  <- lower is better" if k in BAD else ""
    print(f"  {k:<30}{b[k]}/{b['n']:<8}{p[k]}/{p['n']}{flag}")
print("  " + "-" * 51)
for arm in ARMS:
    m = cons[arm]
    if m["n"]:
        print(f"  {arm:<10} ingest {m['ingest']//m['n']:>9,} tok/run   {m['turns']/m['n']:.1f} turns/run")
print(f"\n  artifacts: {work}/out\n")
PY
